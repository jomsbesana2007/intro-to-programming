# Turn your if-else chain from Exercise 5-4 into an if-elif-else chain.

# •	 If the alien is green, print a message that the player earned 5 points.
# •	 If the alien is yellow, print a message that the player earned 10 points.
# •	 If the alien is red, print a message that the player earned 15 points.
# •	 Write three versions of this program, making sure each message is printed for the appropriate color alien.

# The program that runs the if block
alien_color = 'green'

if alien_color == 'green':
    print("Congratulations, the color of the alien is green! You've just earned 5 points!")
elif alien_color == 'yellow':
    print("Congratulations, the color of the alien is yellow! You've just earned 10 points!")
else:
    print("Congratulations, the color of the alien is red! You've just earned 15 points!")


# The program that runs the elif block
alien_color = 'yellow'

