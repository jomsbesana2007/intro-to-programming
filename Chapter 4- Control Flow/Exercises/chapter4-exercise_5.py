# The list of my favorite fruits

favorite_fruits = ['Apple', 'Banana', 'Kiwi']

# The conditions are checked against the fruits list, and a message is printed when a match is found in the favorite_fruits list

if 'Apple' in favorite_fruits:
    print("Your favorite are crisp apples!")

if 'Kiwi' in favorite_fruits:
    print("Your favorite are tangy kiwis!")

if 'Cucumber' in favorite_fruits:
    print("Your favorite are refreshing cucumbers!")

if 'Strawberries' in favorite_fruits:
    print("Your favorite are juicy strawberries!")

if 'Durian' in favorite_fruits:
    print("Your favorite are smelly and exotic durians!")
