## Exercise 2: Favorite Book

# Write a function called favorite_book() that accepts one parameter, title. 

# The function should print a message, such as One of my favorite books is Alice in Wonderland. 

# Call the function, making sure to include a book title as an argument in the function call.


# The favorite_book function that prints out the user's favorite book
def favorite_book(title):
    print(f"The book that I love reading the most is {title}")

# The function call containing a parameter
favorite_book("Diary of a Wimpy Kid")